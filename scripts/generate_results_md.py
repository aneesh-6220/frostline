#!/usr/bin/env python3
"""Render docs/RESULTS.md from data/processed/*.csv and *.json so no number is typed by hand.

Usage (repo root): python3 -I scripts/generate_results_md.py
A test (tests/test_scientific_acceptance.py) fails if docs/RESULTS.md differs from this script's output.
"""
import json
import os
import sys

import numpy as np
import pandas as pd

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = lambda *a: os.path.join(ROOT, *a)
rd = lambda f: pd.read_csv(P("data/processed", f))
tr = rd("trend_results.csv")
mt = rd("multiple_testing_126.csv")
rr = rd("road_record_trends_all_routes.csv")
hs = rd("headline_trend_sensitivity.csv")
cor = rd("road_climate_correlations.csv")
snow = rd("snow_vs_opening.csv")
snt = rd("snow_trends.csv")
lk = rd("leakage_audit.csv")
reg = rd("regional_comparison.csv")
bym = pd.read_csv(P("data/processed/diagnostics/bias_by_month.csv"))
dg = json.load(open(P("data/processed/diagnostics/diagnostics_summary.json")))
rs = json.load(open(P("data/processed/remediation_summary.json")))
ro = rd("road_operations.csv")


def p3(p):
    if pd.isna(p):
        return "n/a"
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def ci(lo, hi, d=2):
    return f"{lo:.{d}f} to {hi:.{d}f}"


def sgn(x, d=2):
    return f"{x:+.{d}f}"


L = []
w = L.append
w("# Results (generated file; do not edit by hand)\n")
w("Generated by `python3 -I scripts/generate_results_md.py` from `data/processed/`. Regenerate the data first with `python3 -I scripts/regenerate_all.py`.\n")
w("## 0. Status and rules for reading these numbers\n")
w("- Everything here is **exploratory**. No hypotheses were registered in advance of the data being examined. Dettah was chosen as the primary route after its road-date trend had been seen, so Dettah findings are selection-biased; the selection-adjusted view is in section 4.")
w("- `p` is the unadjusted Mann-Kendall two-sided p-value; `q` is a Benjamini-Hochberg adjusted value for the stated family. A small p in a short record with many tests is weak evidence.")
w("- Temperature series are NASA POWER T2M, a MERRA-2 reanalysis value for a 0.5 x 0.625 degree cell, **not an observation**. Trends are Theil-Sen slopes per decade with 95% confidence intervals; `block CI` is a moving-block bootstrap interval that allows for short-range serial dependence.")
w("- Nothing here is a statement of cause, a road-safety statement, or a prediction.\n")

# 1 bias
e = dg["effect_on_metrics"]
w("## 1. NASA T2M versus the Yellowknife A station (cell containing Dettah)\n")
ob = dg["overall_bias_all_days"]
w(f"Paired days with a station mean: {ob['n']}. Mean bias (NASA minus station): {ob['mean_bias']:+.2f} C all days; {dg['overall_bias_Oct_Dec']['mean_bias']:+.2f} C in Oct-Dec; {dg['overall_bias_Jan_Mar']['mean_bias']:+.2f} C in Jan-Mar. Lag 0 is best, so this is not a date shift; the bias is seasonal (below), stable between the two station eras, and shows no drift. Cause is not established (`docs/TEMPERATURE_BIAS_DIAGNOSIS.md`).\n")
w("| Month | " + " | ".join(str(int(m)) for m in bym.month) + " |")
w("|---|" + "---|" * len(bym))
w("| Mean bias (C) | " + " | ".join(f"{v:+.2f}" for v in bym.mean_bias) + " |\n")
w(f"On the {e['winters_with_complete_Oct_Dec_in_both']} winters with complete Oct-Dec data in both series, NASA mean Oct-Dec FDD is {e['fdd_mean_nasa']:.0f} C-days versus {e['fdd_mean_station']:.0f} at the station (NASA {e['fdd_pct_overestimate']:+.1f}%); the year-to-year correlation is {e['fdd_nasa_station_pearson_r']:.2f} (Spearman {e['fdd_nasa_station_spearman_r']:.2f}). "
  f"Oct-Dec FDD slope on those winters: NASA {e['fdd_slope_nasa_same_winters']['slope_per_decade']:+.1f} (CI {ci(e['fdd_slope_nasa_same_winters']['ci_low'], e['fdd_slope_nasa_same_winters']['ci_high'], 0)}) vs station {e['fdd_slope_station_same_winters']['slope_per_decade']:+.1f} (CI {ci(e['fdd_slope_station_same_winters']['ci_low'], e['fdd_slope_station_same_winters']['ci_high'], 0)}) C-days per decade; neither differs from zero and the difference between them ({e['fdd_diff_slope_nasa_minus_station']['slope_per_decade']:+.1f}, CI {ci(e['fdd_diff_slope_nasa_minus_station']['ci_low'], e['fdd_diff_slope_nasa_minus_station']['ci_high'], 0)}) is not distinguishable from zero. "
  f"Jan-Mar thaw days: NASA mean {e['thaw_days_mean_nasa']:.2f} versus station {e['thaw_days_mean_station']:.2f} per winter, so NASA thaw counts under-detect thaw.\n")
w("**Allowed:** use NASA series for year-to-year variation and for trends with their intervals. **Not allowed:** use NASA absolute FDD, mean temperature or thaw-day counts as local conditions, ice thickness or safety indicators.\n")

# 2 climate trends
w("## 2. NASA climate trends at Dettah and Aklavik (2001/02 to 2024/25, n = 24 winters)\n")
w("| Metric | Dettah slope per decade (95% CI), p, q | Aklavik slope per decade (95% CI), p, q |")
w("|---|---|---|")
labels = [("mean_octdec_c", "Oct-Dec mean temperature (C)", 2), ("mean_janmar_c", "Jan-Mar mean temperature (C)", 2), ("fdd_octdec", "Oct-Dec FDD (C-days)", 0),
          ("tmax_mean_mar15_apr15_c", "Mar 15 to Apr 15 mean daily max (C)", 2)]
for key, lab, d in labels:
    cells = []
    for loc in ("dettah_bay", "aklavik_delta"):
        r = mt[(mt.location_id == loc) & (mt.metric == key)].iloc[0]
        cells.append(f"{sgn(r.slope_per_decade, d)} ({ci(r.ci95_low, r.ci95_high, d)}), p {p3(r.p_unadjusted)}, q {p3(r.q_bh_all126)}")
    w(f"| {lab} | " + " | ".join(cells) + " |")
for key, lab, d in [("mean_full_c", "Full-season mean (C)", 2), ("fdd_pre_cutoff", "FDD to the day before the earliest opening (C-days)", 0)]:
    cells = []
    for loc in ("dettah_bay", "aklavik_delta"):
        r = tr[(tr.location_id == loc) & (tr.metric == key) & (tr.variant == "main (2001-2024)")].iloc[0]
        cells.append(f"{sgn(r.slope_per_decade, d)} ({ci(r.ci95_low, r.ci95_high, d)}), p {p3(r.mk_p)}, q not computed")
    w(f"| {lab} | " + " | ".join(cells) + " |")
_cl = pd.read_csv(P("UI/data_real/climate_annual.csv"))
def _thaw(cid):
    t = _cl[(_cl.corridor_id == cid) & (_cl.metric == "thaw_days")].value
    return f"not estimated (thaw in {int((t > 0).sum())} of {len(t)} winters; total thaw days {int(t.sum())})"
w(f"| Jan-Mar thaw days | {_thaw('dettah_bay')} | {_thaw('aklavik_delta')} |\n")
w("`q` is across all 126 extended trend tests (section 3). The last two rows are outside that family (extra tests), so no adjusted value is given; the Aklavik pre-opening FDD result is a post-hoc window and should not be headlined. Sensitivity variants (drop first or last 5 winters, OLS) are in `trend_results.csv`.\n")

# 3 multiplicity
x = rs["extended_126"]
w("## 3. Multiple testing\n")
w(f"The extended analysis runs {x['n_tests_with_p']} trend tests (14 metrics x 9 corridors). {x['nominal_p_lt_0.05']} have p < 0.05; about {x['expected_false_positives_at_0.05']} would be expected by chance if no trends existed. "
  f"With Benjamini-Hochberg across all {x['n_tests_with_p']}: **{x['bh_q_lt_0.05_all126']} tests have q < 0.05** and {x['bh_q_lt_0.10_all126']} have q < 0.10; Holm (family-wise) leaves {x['holm_lt_0.05_all126']} at 0.05. "
  f"The three at q < 0.10 are: " + "; ".join(f"{s['location_id']} {s['metric']} (p {p3(s['p_unadjusted'])}, q {p3(s['q_bh_all126'])})" for s in x["survivors_q_lt_0.10"]) + ". Autocorrelation flagged (|lag-1| > 0.3) in " f"{x['autocorr_flagged']} of the series.\n")
w(f"By family: climate metrics only: {x['climate_family']['n']} tests, {x['climate_family']['nominal']} nominal, {x['climate_family']['bh_q_lt_0.05']} at q < 0.05. Road dates only: {x['road_family']['n']} tests, {x['road_family']['nominal']} nominal, {x['road_family']['bh_q_lt_0.05']} at q < 0.05 ({x['road_family']['bh_q_lt_0.10']} at q < 0.10). Full table: `multiple_testing_126.csv`; family definitions: `hypothesis_families.csv`.\n")
w("**Reading:** no NASA climate trend (temperature, precipitation, wind, humidity, radiation) in any of the nine corridors survives correction. Road-date trends are a different matter and are examined next.\n")

# 4 roads
a = rs["road_record_all_routes"]
w("## 4. Road opening and closing dates\n")
w("Day numbers count days since Oct 1; positive opening-day slope means later opening. The interval (close minus open) is **not** usable days: opening dates mark the start of public traffic (for Dettah first for vehicles under 5,000 kg), and temporary closures are not recorded.\n")
w("| Road | Record | Metric | Slope per decade (95% CI) | Block CI | p | q (family) |")
w("|---|---|---|---|---|---|---|")
for rid, rn in (("dettah", "Dettah"), ("aklavik", "Aklavik")):
    for metric, mname in (("open_day", "opening day"), ("close_day", "closing day"), ("open_to_close_days", "open-to-close interval")):
        r = rr[(rr.road_id == rid) & (rr.metric == metric)].iloc[0]
        w(f"| {rn} | 1993-2024 (n {int(r.n_seasons)}) | {mname} | {sgn(r.slope_per_decade, 1)} ({ci(r.ci95_low, r.ci95_high, 1)}) | {ci(r.bb_ci95_low, r.bb_ci95_high, 1)} | {p3(r.p_unadjusted)} | {p3(r.q_bh_all_routes)} (all-route family) |")
        h = mt[(mt.location_id == ("dettah_bay" if rid == "dettah" else "aklavik_delta")) & (mt.metric == metric)].iloc[0]
        w(f"| {rn} | 2001-2024 (n {int(h.n)}) | {mname} | {sgn(h.slope_per_decade, 1)} ({ci(h.ci95_low, h.ci95_high, 1)}) | {ci(h.bb_ci95_low, h.bb_ci95_high, 1)} | {p3(h.p_unadjusted)} | {p3(h.q_bh_all126)} (126-test family) |")
w("")
w(f"**Selection adjustment.** Dettah was picked after its trend was seen. Across all {a['n_routes']} NWT routes with at least 15 verified winters (full 1993-2024 record, {a['n_tests_with_p']} tests: opening day, closing day, interval per route), {a['nominal_p_lt_0.05']} have p < 0.05 and {a['bh_q_lt_0.05']} have q < 0.05; Holm leaves {a['holm_lt_0.05']}. "
  "Dettah's later opening and shorter interval are among those that survive (q values above), so the result is not simply the best of 17 routes. The tests across routes are not independent (shared weather, shared operator and policy changes), so q values are indicative.\n")
sv = rr[rr.q_bh_all_routes < 0.05]
def _names(metric, sign):
    x = sv[(sv.metric == metric) & ((sv.slope_per_decade > 0) if sign > 0 else (sv.slope_per_decade < 0))]
    return ", ".join(sorted(x.road_id)) or "none"
w("Routes with q < 0.05 in the all-route family, by direction (computed from `road_record_trends_all_routes.csv`):\n")
w(f"- Later opening: {_names('open_day', 1)}. Earlier opening: {_names('open_day', -1)}.")
w(f"- Later closing: {_names('close_day', 1)}. Earlier closing: {_names('close_day', -1)}.")
w(f"- Longer open-to-close interval: {_names('open_to_close_days', 1)}. Shorter: {_names('open_to_close_days', -1)}.\n")
w("The signs are mixed across routes, so there is no single regional signal, and Dettah is in the minority (later opening, shorter interval). The record is a government record of operations, not an ice measurement.\n")
w("Robustness of the Dettah opening-day trend (Theil-Sen per decade; lag-1 residual autocorrelation):\n")
w("| Variant | n | slope (95% CI) | block CI | p | lag-1 |")
w("|---|---|---|---|---|---|")
for _, r in hs[(hs.road_id == "dettah") & (hs.metric == "open_day")].iterrows():
    w(f"| {r.variant} | {int(r.n)} | {r.theil_sen_per_decade:+.1f} ({ci(r.ts_ci95_low, r.ts_ci95_high, 1)}) | {ci(r.bb_ci95_low, r.bb_ci95_high, 1)} | {p3(r.mk_p_unadjusted)} | {r.lag1_resid:+.2f} |")
w("")
w("Serial correlation is small for the Dettah road-date series (the 0.3 flag is not triggered), so prewhitening is not justified and was not applied. Dropping the first five winters leaves a positive slope; its Theil-Sen interval touches zero (the block-bootstrap interval does not), so the later-opening result is sensitive to the early years.\n")
w("Aklavik's 1993-2024 opening-day trend (earlier) is not present in 2001-2024; call it fragile. Aklavik's interval trend differs in sign from Dettah's.\n")

# 5 associations
w("## 5. Associations between climate predictors and road dates (leak-free, exploratory)\n")
w("Earlier versions used predictor windows that extend past the outcome date. Audit (`leakage_audit.csv`): " 
  f"the Oct 1 to Dec 31 window reaches or passes the Dettah opening date in {rs['leakage']['dettah_oct_dec_vs_opening_leaky_winters']} of 24 winters and the Aklavik opening date in {rs['leakage']['aklavik_oct_dec_vs_opening_leaky_winters']} of 24; the Mar 15 to Apr 15 window reaches the Dettah closing date in {rs['leakage']['dettah_mar15_apr15_vs_closing_leaky_winters']} of 24. "
  "Those pairs were removed. Each remaining predictor window ends the day before the earliest opening (or closing) ever recorded for that road, so it ends before the outcome in every winter by construction.\n")
w("| Road | Predictor (window) | Outcome | Spearman rho (block CI) | n | p | q (family) |")
w("|---|---|---|---|---|---|---|")
for _, r in cor.iterrows():
    w(f"| {'Dettah' if r.location_id == 'dettah_bay' else 'Aklavik'} | {r.climate_metric} ({r.predictor_window}) | {r.road_metric} | {r.spearman_rho:+.2f} ({ci(r.ci95_low, r.ci95_high)}) | {int(r.n)} | {p3(r.p_unadjusted)} | {p3(r.q_bh_family)} |")
w("")
w("None is distinguishable from zero. The Dettah closing association that looked moderate with the leaky window (rho -0.34) is about zero once the window ends before closing.\n")
w("Snow at Yellowknife A versus Dettah opening day (n about 24; family of 5 snow predictors, BH q and Bonferroni shown):\n")
w("| Predictor | Leak-free vs full record | rho (block CI) | n | p | q | Bonferroni |")
w("|---|---|---|---|---|---|---|")
for _, r in snow.iterrows():
    lf = "yes" if r.leak_free_vs_full_1993_2024_record else ("sample only" if r.leak_free_in_2001_2024_sample else "no (uses days after some openings)")
    w(f"| {r.predictor} | {lf} | {r.spearman_rho:+.2f} ({ci(r.ci95_low, r.ci95_high)}) | {int(r.n)} | {p3(r.p_unadjusted)} | {p3(r.q_bh_family)} | {p3(r.bonferroni_5)} |")
w("")
tr_s = snt.set_index("series")
w("Snow-on-ground at Nov 28 (the last day before the earliest-ever opening) is positively associated with later Dettah openings, and the association survives the snow-family correction. It has a trend of "
  f"{tr_s.loc['sog_nov28_cm', 'slope_per_decade']:+.1f} cm per decade (CI {ci(tr_s.loc['sog_nov28_cm', 'ci95_low'], tr_s.loc['sog_nov28_cm', 'ci95_high'], 1)}), so the record does **not** show that snow cover changed, and therefore does not show that snow cover accounts for the opening trend. "
  "Opening depends on ice thickness, overflow, snow, construction timing and decisions; an association with an airport snow measurement is a hint, not a mechanism.\n")

# 6 regional
w("## 6. Climate difference between the two NASA cells (Dettah minus Aklavik)\n")
w("This compares the climate series of two grid cells only. The roads are different objects (see `docs/ROUTE_IDENTITY.md`), so it says nothing about road dates.\n")
w("| Metric | Difference slope per decade (95% CI) | p |")
w("|---|---|---|")
for _, r in reg.iterrows():
    if r.status == "ok":
        w(f"| {r.metric} | {r.diff_slope_per_decade:+.2f} ({ci(r.ci95_low, r.ci95_high)}) | {p3(r.mk_p)} |")
w("\nNo difference is supported; do not describe the locations as trending differently.\n")

# 7 data corrections
bad = ro[ro.record_status == "flagged_inconsistent"]
w("## 7. Data corrections in this run\n")
w(f"The road-date validator accepted two Tibbitt-Contwoyto rows with impossible dates (opening in February of the season start year, giving 413 and 416 day intervals). It now requires an opening in Oct-Dec of the season start year or Jan-May of the next. {len(bad)} rows are flagged inconsistent and excluded, not corrected (raw dates fail the date checks; see `record_note` in `road_operations.csv`; confirm with GNWT before any correction): " 
  + "; ".join(f"{r.road_id} {int(r.season_start_year)}" for _, r in bad.iterrows()) + ". Counts above were regenerated after this fix.\n")

# 8 unresolved
w("## 8. Not obtained or not verified\n")
w("- MERRA-2 via Giovanni (needs an Earthdata login) and MODIS products were not obtained; POWER T2M equals MERRA-2 T2M only per the provider.")
w("- The physical cause of the cold bias is unknown.")
w("- Route alignment and segment for the Aklavik ice road, and whether the sampled grid cell represents each road, are unverified (`docs/ROUTE_IDENTITY.md`).")
w("- The POWER record was not extended before 2001; the road record begins 1993.")
OUT = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else P("docs/RESULTS.md")
open(OUT, "w").write("\n".join(L).replace(chr(8212), "-").replace("–", "-") + "\n")
print(OUT, "written")
