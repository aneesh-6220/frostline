import { BriefDownloads } from "../components/domain";
import { Caption, ErrorState, Fetching, PageHeader, Skeleton } from "../components/ui";
import { useBriefHtml } from "../lib/api";
import { period, useInv } from "../lib/investigation";

export default function Brief() {
  const { boot, sel, question } = useInv();
  const { data, error, isFetching } = useBriefHtml(sel, question);
  const v = boot.variables[sel.var];
  const loc = boot.locations[sel.loc];
  return (
    <div>
      <PageHeader eyebrow="Frostline Evidence Brief" title="Leave with a finding you can reproduce"
        lede={`${v.label} · ${loc.name} · winters ${period(sel.first, sel.last)}. The brief is assembled from the same analysis objects as the screens, so every number in it equals the number you saw. No language model writes any part of it.`} />
      <BriefDownloads sel={sel} question={question} />
      <Caption className="mb-8">
        HTML: a self-contained report with an embedded chart; open it in any browser and print to PDF if needed. CSV: the per-winter values and the fitted trend. JSON: the full
        analysis record with file hashes for reproduction. Change the investigation and the brief follows.
      </Caption>
      {error ? <ErrorState error={error} /> : (
        <div className="card relative overflow-hidden">
          <Fetching active={isFetching} />
          <div className="flex items-center gap-2 border-b border-line bg-subtle px-4 py-2.5">
            <span className="size-2.5 rounded-full bg-[#dbe3ee]" /><span className="size-2.5 rounded-full bg-[#dbe3ee]" /><span className="size-2.5 rounded-full bg-[#dbe3ee]" />
            <span className="ml-3 truncate font-mono text-[11.5px] text-ink-3">Preview · Evidence Brief</span>
          </div>
          {data ? (
            // The brief is generated by this app from escaped values; it is never user-supplied HTML. Its chart is inline SVG, so the frame runs fully sandboxed.
            <iframe title="Evidence Brief preview" srcDoc={data} sandbox="" className="h-[900px] w-full bg-white max-sm:h-[75dvh]" />
          ) : <Skeleton className="m-6 h-[600px]" />}
        </div>
      )}
    </div>
  );
}
