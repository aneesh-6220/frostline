"""Evidence Brief view: preview and download the report for the current investigation."""
import streamlit as st

from .. import analysis as an
from .. import fmt, ui


def render(ds):
    inv = ui.current()
    loc, var = an.locations(ds)[inv.location_id], inv.variable
    ui.page_header("Frostline Evidence Brief", "Leave with a finding you can reproduce",
                   f"{var.label} · {loc.name} · winters {fmt.period(inv.first, inv.last)}. The brief is assembled from the same analysis objects as the screens, "
                   "so every number in it equals the number you saw. No language model writes any part of it.")
    b = ui.brief_downloads(ds, inv, key="brief")
    ui.html("<div class='fl-src' style='margin:var(--s2) 0 var(--s5)'>HTML: a self-contained report with an embedded chart; open it in any browser and print to PDF if needed. "
            "CSV: the per-winter values and the fitted trend. JSON: the full analysis record with file hashes for reproduction. Change the investigation in the sidebar and the brief follows.</div>")
    with st.container(border=True):
        # the brief is generated by this app from escaped values; it is never user-supplied HTML
        st.iframe(b.html, height=900)
